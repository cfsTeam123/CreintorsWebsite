export type ProductSpec = { label: string; value: string; highlight?: boolean };

/**
 * The two product lines Teknosol builds. They share a card but not a spec
 * vocabulary — a test stand is described by reaction force and test pressure,
 * a steel-plant part by its part number and the mill it was supplied to — so
 * each is its own track in TEK_LAYERS rather than one mixed portfolio.
 */
export type ProductFamily = "test-stand" | "steel-plant" |"foaming-line";

export type TekTrackId =
	| "test-rigs"
	| "foaming-line"
	| "steel"
	| "honing"
	| "satellite-docket"
	| "business-excellence";

export type TekTrack = {
	id: TekTrackId;
	label: string;
	/** The product family this track lists. Tracks without one show `overview`. */
	family?: ProductFamily;
	/** One line under the track's heading. */
	blurb?: string;
	/** For a track with no products supplied yet: the copy of its enquiry panel. */
	overview?: string;
};

